"""

    # Add hyetograph for the largest scenario (2.0 inch)
    # In practice, we'd create separate plans per scenario
    total_inches = 2.0
    flow_content += f"Precip Total={total_inches}\n"
    flow_content += "Precip Time Interval=6MIN\n"

    # Generate incremental rainfall from SCS Type II
    flow_content += "Precip Hyetograph=\n"
    prev_frac = 0
    for t, frac in SCS_TYPE2_1HR:
        incr = (frac - prev_frac) * total_inches
        flow_content += f"  {incr:.4f}\n"
        prev_frac = frac

    # Downstream boundary - normal depth
    flow_content += """
