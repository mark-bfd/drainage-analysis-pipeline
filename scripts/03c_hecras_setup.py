def main():
    import argparse

    parser = argparse.ArgumentParser(
        description='Set up HEC-RAS 2D project for storm simulation'
    )
    parser.add_argument('--dsm', required=True, help='Path to terrain GeoTIFF (resampled to 30cm)')
    parser.add_argument('--config', '-c', help='Community config JSON')
    parser.add_argument('--output', '-o', required=True, help='HEC-RAS project directory')
    parser.add_argument('--run', action='store_true',
                        help='Run simulation after setup (requires mesh to be created in GUI first)')

    args = parser.parse_args()

    config = {}
    if args.config:
        p = Path(args.config)
        if p.exists():
            with open(p) as f:
                config = json.load(f)

    project_dir = Path(args.output)
    terrain_path = Path(args.dsm)

    print(f"\n{'='*60}")
    print("HEC-RAS 2D Project Setup")
    print(f"{'='*60}\n")

    # Verify HEC-RAS installation
    if not HECRAS_EXE.exists():
        print(f"ERROR: HEC-RAS not found at {HECRAS_EXE}")
        print("Install HEC-RAS 6.6 from: https://www.hec.usace.army.mil/software/hec-ras/")
        sys.exit(1)

    print(f"  HEC-RAS: {HECRAS_EXE}")
    print(f"  Terrain: {terrain_path}")
    print(f"  Project: {project_dir}")

    # Create project
    files = create_project_structure(project_dir, terrain_path, config)

    # Generate and display instructions
    instructions = generate_gui_instructions(project_dir, config)
    print(instructions)

    # Save instructions to file
    instructions_path = project_dir / "SETUP_INSTRUCTIONS.txt"
    instructions_path.write_text(instructions)
    print(f"Instructions saved to: {instructions_path}")

    # Optionally run (only works after GUI mesh setup)
    if args.run:
        prj_file = Path(files['project_file'])
        geom_hdf = project_dir / f"{PROJECT_NAME}.g01.hdf"
        if geom_hdf.exists():
            print("\nRunning simulation...")
            success = run_hecras(prj_file)
            if success:
                results = extract_results(project_dir)
                print(f"Results: {results}")
        else:
            print("\nCannot run yet — mesh not created.")
            print("Complete the GUI setup steps first, then re-run with --run")

    # Save setup metadata
    setup_meta = {
        'timestamp': datetime.now().isoformat(),
        'hecras_version': '6.6',
        'project_dir': str(project_dir),
        'terrain': str(terrain_path),
        'files': files,
        'scenarios': RAINFALL_SCENARIOS,
        'status': 'project_created_awaiting_mesh_setup'
    }
    meta_path = project_dir / "setup_metadata.json"
    with open(meta_path, 'w') as f:
        json.dump(setup_meta, f, indent=2)

    print(f"\n{'='*60}")
    print("Project created. Complete GUI setup, then automation takes over.")
    print(f"{'='*60}\n")


if __name__ == '__main__':
    main()
