"""
03c_hecras_setup.py - HEC-RAS 2D Project Setup & Automation
Drone Drainage Analysis Pipeline

Creates a HEC-RAS 2D rain-on-grid project from drone DSM data,
runs GPU-accelerated storm simulations, and extracts results.

This script:
1. Creates HEC-RAS project structure (terrain, geometry, plans)
2. Generates precipitation boundary conditions for each scenario
3. Runs simulations via command line (GPU-accelerated)
4. Extracts depth/velocity results from HDF5 output

Prerequisites:
- HEC-RAS 6.6 installed at C:\\Program Files (x86)\\HEC\\HEC-RAS\\6.6\\
- NVIDIA GPU with OpenCL support (for GPU acceleration)
- Python packages: h5py, rashdf, numpy, rasterio

Usage:
    python 03c_hecras_setup.py --dsm terrain.tif --output ./hecras --config config.json

NOTE: The initial mesh creation must be done in RAS Mapper GUI.
This script prepares all files and provides step-by-step instructions
for the one-time GUI setup, then automates everything else.
"""

