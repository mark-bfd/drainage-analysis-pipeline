def run_hecras(project_file: Path, verbose: bool = True) -> bool:
    """Run HEC-RAS simulation via command line."""
    if not HECRAS_EXE.exists():
        print(f"ERROR: HEC-RAS not found at {HECRAS_EXE}")
        return False

    cmd = [str(HECRAS_EXE), "-c", str(project_file)]
    if verbose:
        print(f"  Running: {' '.join(cmd)}")

    result = subprocess.run(cmd, capture_output=True, text=True, timeout=3600)

    if result.returncode == 0:
        if verbose:
            print("  HEC-RAS computation completed successfully")
        return True
    else:
        if verbose:
            print(f"  HEC-RAS computation failed (exit code {result.returncode})")
            if result.stderr:
                print(f"  stderr: {result.stderr[:500]}")
        return False


def extract_results(project_dir: Path, plan_name: str = "p01",
                    verbose: bool = True) -> Dict:
    """Extract simulation results from HEC-RAS HDF5 output."""
    results = {}

    plan_hdf = project_dir / f"{PROJECT_NAME}.{plan_name}.hdf"
    if not plan_hdf.exists():
        if verbose:
            print(f"  No results HDF found: {plan_hdf}")
        return results

    try:
        import rashdf
        # Use rashdf to extract results
        if verbose:
            print(f"  Reading results from {plan_hdf}")

        with h5py.File(str(plan_hdf), 'r') as f:
            # Navigate the HDF5 structure
            if 'Results' in f and 'Unsteady' in f['Results']:
                unsteady = f['Results']['Unsteady']
                if 'Output' in unsteady:
                    output = unsteady['Output']
                    if 'Output Blocks' in output:
                        # Get max depth across time
                        # The structure varies by HEC-RAS version
                        pass

            results['hdf_path'] = str(plan_hdf)
            results['status'] = 'results_available'

    except Exception as e:
        if verbose:
            print(f"  Error reading results: {e}")
        results['error'] = str(e)

    return results


